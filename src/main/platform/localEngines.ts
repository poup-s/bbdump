/**
 * The local server of MySQL, MariaDB and MongoDB: how each system installs and starts it.
 * Pure (commands and scripts only): localEngineServer.ts runs them.
 * - macOS: Homebrew (mysql, mariadb, mongodb/brew/mongodb-community), started with brew services.
 * - Linux: the distribution's packages through pkexec, with an account for bbdump created by
 *   the script (MySQL and MariaDB only: MongoDB is not in the distributions' repositories).
 * - Windows: winget (MongoDB silently; MariaDB with its installer, which asks for the root
 *   password). MySQL has no winget server package: its installer, by hand.
 */
import type { LinuxFamily } from '../../types/setup';

export type LocalEngine = 'mysql' | 'mariadb' | 'mongodb';

export const LOCAL_ENGINES: readonly LocalEngine[] = ['mysql', 'mariadb', 'mongodb'];

export const LOCAL_ENGINE_PORT: Record<LocalEngine, number> = { mysql: 3306, mariadb: 3306, mongodb: 27017 };

/** The account bbdump creates when it can (Homebrew MariaDB, Linux): never root itself */
export const LOCAL_ACCOUNT = 'bbdump';

export function isLocalEngine(value: unknown): value is LocalEngine {
    return typeof value === 'string' && (LOCAL_ENGINES as readonly string[]).includes(value);
}

const BREW_FORMULA: Record<LocalEngine, string> = { mysql: 'mysql', mariadb: 'mariadb', mongodb: 'mongodb/brew/mongodb-community' };
const BREW_SERVICE: Record<LocalEngine, string> = { mysql: 'mysql', mariadb: 'mariadb', mongodb: 'mongodb-community' };

/** Homebrew: the commands, in order (MongoDB's formula lives in MongoDB's own tap) */
export function macosLocalSteps(engine: LocalEngine, brew: string): string[][] {
    return [
        ...(engine === 'mongodb' ? [[brew, 'tap', 'mongodb/brew']] : []),
        [brew, 'install', BREW_FORMULA[engine]],
        [brew, 'services', 'start', BREW_SERVICE[engine]],
    ];
}

export function macosStartStep(engine: LocalEngine, brew: string): string[] {
    return [brew, 'services', 'start', BREW_SERVICE[engine]];
}

/** The server's daemon, to tell "installed" from "not installed" */
export const SERVER_BINARIES: Record<LocalEngine, string[]> = {
    mysql: ['mysqld'],
    mariadb: ['mariadbd', 'mysqld'],
    mongodb: ['mongod'],
};

/** Homebrew's own copies (found even when its bin folder is not in the app's PATH) */
export function brewBinaryCandidates(engine: LocalEngine): string[] {
    const name = engine === 'mongodb' ? 'mongodb-community' : engine;
    return ['/opt/homebrew/opt', '/usr/local/opt'].flatMap(prefix => SERVER_BINARIES[engine].map(bin => `${prefix}/${name}/bin/${bin}`));
}

interface LinuxPackages { install: string; packages: string[]; service: string; client: string; init?: string[] }

/** The distribution's packages of a server, or null when it has none (MongoDB, MySQL on Arch / SUSE) */
export function linuxLocalPackages(engine: LocalEngine, family: LinuxFamily): LinuxPackages | null {
    if (engine === 'mongodb' || family === 'unknown') return null;
    if (engine === 'mariadb') {
        if (family === 'debian') return { install: 'DEBIAN_FRONTEND=noninteractive apt-get install -y', packages: ['mariadb-server'], service: 'mariadb', client: 'mariadb' };
        if (family === 'fedora') return { install: 'dnf install -y', packages: ['mariadb-server'], service: 'mariadb', client: 'mariadb' };
        if (family === 'suse') return { install: 'zypper --non-interactive install', packages: ['mariadb'], service: 'mariadb', client: 'mariadb' };
        return {
            install: 'pacman -S --noconfirm --needed', packages: ['mariadb'], service: 'mariadb', client: 'mariadb',
            init: ['if [ ! -d /var/lib/mysql/mysql ]; then mariadb-install-db --user=mysql --basedir=/usr --datadir=/var/lib/mysql; fi'],
        };
    }
    if (family === 'debian') return { install: 'DEBIAN_FRONTEND=noninteractive apt-get install -y', packages: ['mysql-server'], service: 'mysql', client: 'mysql' };
    if (family === 'fedora') return { install: 'dnf install -y', packages: ['community-mysql-server'], service: 'mysqld', client: 'mysql' };
    return null;
}

/**
 * The root script for Linux: install, start at boot, then an account for bbdump (root itself
 * only answers the system's root through its socket). `password` is generated by bbdump: hex.
 */
export function linuxLocalScript(engine: LocalEngine, family: LinuxFamily, password: string): string | null {
    const spec = linuxLocalPackages(engine, family);
    if (!spec) return null;
    if (!/^[0-9a-f]{16,128}$/.test(password)) throw new Error('Invalid generated password');
    const account = (host: string) => `'${LOCAL_ACCOUNT}'@'${host}'`;
    const sql = [
        `CREATE USER IF NOT EXISTS ${account('localhost')} IDENTIFIED BY '${password}'`,
        `CREATE USER IF NOT EXISTS ${account('127.0.0.1')} IDENTIFIED BY '${password}'`,
        `ALTER USER ${account('localhost')} IDENTIFIED BY '${password}'`,
        `ALTER USER ${account('127.0.0.1')} IDENTIFIED BY '${password}'`,
        `GRANT ALL PRIVILEGES ON *.* TO ${account('localhost')} WITH GRANT OPTION`,
        `GRANT ALL PRIVILEGES ON *.* TO ${account('127.0.0.1')} WITH GRANT OPTION`,
        'FLUSH PRIVILEGES',
    ].join('; ');
    return [
        '#!/bin/bash',
        `# bbdump setup: ${engine} server (${family})`,
        'set -euo pipefail',
        'export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin',
        'step() { echo "==> [$1%] $2"; }',
        '',
        `step 10 "Installing ${spec.packages.join(', ')}"`,
        ...(family === 'debian' ? ['apt-get update'] : []),
        `${spec.install} ${spec.packages.join(' ')}`,
        ...(spec.init ?? []),
        '',
        `step 60 "Starting ${spec.service} and enabling it at boot"`,
        'if command -v systemctl >/dev/null 2>&1 && [ -d /run/systemd/system ]; then',
        `  systemctl enable --now ${spec.service}`,
        'else',
        `  service ${spec.service} start`,
        'fi',
        '',
        'step 75 "Waiting for the server"',
        'READY=0',
        'for _ in $(seq 1 30); do',
        `  if ${spec.client} -e "SELECT 1" >/dev/null 2>&1; then READY=1; break; fi`,
        '  sleep 1',
        'done',
        'if [ "$READY" != "1" ]; then echo "The server did not answer within 30 seconds" >&2; exit 1; fi',
        '',
        `step 90 "Creating the ${LOCAL_ACCOUNT} account"`,
        `${spec.client} -e "${sql}"`,
        '',
        'step 100 "Server ready"',
        '',
    ].join('\n');
}

export function linuxStartScript(engine: LocalEngine, family: LinuxFamily): string | null {
    const spec = linuxLocalPackages(engine, family);
    const service = spec?.service ?? (engine === 'mongodb' ? 'mongod' : null);
    if (!service) return null;
    return [
        '#!/bin/bash',
        'set -euo pipefail',
        'export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin',
        `if command -v systemctl >/dev/null 2>&1 && [ -d /run/systemd/system ]; then systemctl start ${service}; else service ${service} start; fi`,
        '',
    ].join('\n');
}

const WINGET_ID: Partial<Record<LocalEngine, string>> = { mariadb: 'MariaDB.Server', mongodb: 'MongoDB.Server' };

/**
 * winget's arguments, or null (MySQL: no server package). MariaDB runs its installer, which
 * asks for the root password (typed then once in bbdump); MongoDB installs silently.
 */
export function wingetLocalArgs(engine: LocalEngine): string[] | null {
    const id = WINGET_ID[engine];
    if (!id) return null;
    const common = ['install', '--id', id, '--exact', '--accept-package-agreements', '--accept-source-agreements'];
    return engine === 'mariadb' ? [...common, '--interactive'] : [...common, '--silent', '--disable-interactivity'];
}

/** Windows services of each server (their installers' names) */
export const WINDOWS_SERVICES: Record<LocalEngine, string[]> = { mysql: ['MySQL84', 'MySQL80', 'MySQL'], mariadb: ['MariaDB', 'MySQL'], mongodb: ['MongoDB'] };

/** What to type by hand when bbdump cannot install it */
export function manualLocalInstall(engine: LocalEngine, os: 'macos' | 'linux' | 'windows', family: LinuxFamily = 'unknown'): string {
    if (os === 'macos') return macosLocalSteps(engine, 'brew').map(step => step.join(' ')).join(' && ');
    if (os === 'windows') {
        const args = wingetLocalArgs(engine);
        return args ? `winget ${args.join(' ')}` : 'https://dev.mysql.com/downloads/installer/';
    }
    const spec = linuxLocalPackages(engine, family);
    if (!spec) return engine === 'mongodb' ? 'https://www.mongodb.com/docs/manual/administration/install-on-linux/' : 'https://dev.mysql.com/downloads/repo/';
    return `sudo ${spec.install.replace('DEBIAN_FRONTEND=noninteractive ', '')} ${spec.packages.join(' ')} && sudo systemctl enable --now ${spec.service}`;
}
